// eval-pool.mjs — evaluate the PUSD pool covenant as the 6th input of the
// combined shielded-pool transaction on the BCH 2026 VM.
//
// Uses the CashScript SDK (mr-zwets fork) to build the covenant's redeem script and
// unlocking bytecode with the CORRECT argument ordering, then evaluates the pool
// input against the full 6-input transaction (5 verifier intra-tx inputs + pool).
//
// Runs the covenant paths:
//   - shield/transfer (isUnshield = 0): no public payout output required.
//   - unshield        (isUnshield = 1): a public PUSD payout output (index 1) required.
//
// actionHash binding (Option F): the covenant recomputes
//   SHA256(nf0|nf1|cm0|cm1|publicValueAbs|publicValueSign|assetCategory|newMerkleRoot)
// (each field 32-byte big-endian, digest truncated to 254 bits) and requires it to
// equal the proof's n1 read from the verifier genesis witness. So each scenario
// supplies covenant args that hash to the n1 its (real) proof attests to. The
// scenario proofs are generated by gen-eval-proofs.mjs (build/eval-proofs.json);
// the verifier transaction is the bench's densless-msm vectors with the genesis
// n0/n1 pushes patched to each scenario's PROVEN public inputs (the covenant only
// reads those two pushes; only the pool input — index 5 — is evaluated here).
//
// Usage: node eval-pool.mjs vectors.json poolArtifact.json evalProofs.json
// NOTE: run from ~/zkb/bench-pusd (it resolves @bitauth/libauth + the vectors from
// that project's node_modules); set CASHSCRIPT_SDK to the fork cashscript dist/index.js.
import { readFileSync } from 'node:fs';
import { createVirtualMachineBch2026, sha256, hexToBin, binToHex } from '@bitauth/libauth';
const { Contract } = await import(process.env.CASHSCRIPT_SDK);

const [, , vectorsPath, artifactPath, evalProofsPath] = process.argv;
const vectors = JSON.parse(readFileSync(vectorsPath, 'utf8'));
const artifact = JSON.parse(readFileSync(artifactPath, 'utf8'));
const evalProofs = JSON.parse(readFileSync(evalProofsPath, 'utf8'));

const PUSD_CATEGORY = '2469acc5afa4b10cb5b5c04afb89c3a3ffd61c5da9c01e26d00951cae2a02544';
const VERIFIER_INPUT_INDEX = 3;   // genesis step
const N0_OFFSET = 1825;           // byte offset of n0 (merkleRoot) DATA in genesis unlocking (1824 = push opcode)
const N1_OFFSET = 1792;           // byte offset of n1 (actionHash) DATA in genesis unlocking (1791 = push opcode)

// ── instantiate the contract via the SDK (correct redeem + arg encoding) ──────
// dummy provider: only contract.bytecode + the unlocker are used (no network calls).
const dummyProvider = { network: 'chipnet' };
// contractType 'p2s': the witness = the function args ONLY (no redeem appended), so
// the harness Step model (locking = redeemScript, unlocking = args) evaluates cleanly.
// tx.inputs[i].tokenCategory returns the category in ON-CHAIN (reversed) byte order
// concatenated with the capability byte; the contract compares assetCategory + 0x01,
// so the constructor arg must be the reversed (on-chain) category bytes.
const PUSD_CATEGORY_ONCHAIN = Buffer.from(PUSD_CATEGORY, 'hex').reverse().toString('hex');
const contract = new Contract(artifact, [PUSD_CATEGORY_ONCHAIN], { provider: dummyProvider, contractType: 'p2s' });
const redeemScript = hexToBin(contract.bytecode);

const category = hexToBin(PUSD_CATEGORY);
const mkToken = (capability, commitment, amount) => ({ amount, category, nft: { capability, commitment } });

// ── build + evaluate ONE scenario ────────────────────────────────────────────
// scenario = { label, covenant:{nf0,nf1,cm0,cm1,newMerkleRoot,publicValueAbs,isUnshield} }
// The covenant args are the LE VM-number byte form of the field elements the scenario's
// proof attests to; their SHA256 actionHash equals the n1 we patch into the genesis.
const runScenario = (scenario) => {
  const { label } = scenario;
  const cov = scenario.covenant;
  const nf0 = Buffer.from(cov.nf0, 'hex');
  const nf1 = Buffer.from(cov.nf1, 'hex');
  const cm0 = Buffer.from(cov.cm0, 'hex');
  const cm1 = Buffer.from(cov.cm1, 'hex');
  const newMerkleRoot = Buffer.from(cov.newMerkleRoot, 'hex');
  const publicValueAbs = BigInt(cov.publicValueAbs);
  const isUnshield = BigInt(cov.isUnshield);

  // Patch the verifier genesis unlocking: n0 <- the pool's stored root (the root the
  // proof is anchored to), n1 <- this scenario's proven actionHash. The covenant reads
  // both out of the sibling witness. n0 must equal the pool's stored root (root
  // binding); for the PoC the stored root is the scenario's pre-transition merkleRoot,
  // which the proof carries as public input n0 — read it from the proof's publicSignals.
  const provenRoot = Buffer.from(scenario.merkleRootLE, 'hex');   // LE byte form (matches n0 push)
  const provenActionHash = Buffer.from(scenario.actionHashLE, 'hex'); // LE byte form (matches n1 push)

  const storedRoot = provenRoot;                       // root binding: stored == proven
  const oldNullifierHash = Buffer.alloc(32, 0);
  const currentBalance = 1000n;
  const inCommitment = Buffer.concat([storedRoot, oldNullifierHash]);
  const newNullifierHash = Buffer.from(sha256.hash(Buffer.concat([oldNullifierHash, nf0, nf1])));
  const outCommitment = Buffer.concat([newMerkleRoot, newNullifierHash]);

  const newBalance = currentBalance + publicValueAbs - 2n * isUnshield * publicValueAbs;

  // covenant unlocking via the SDK (correct order)
  const unlocker = contract.unlock.spend(nf0, nf1, cm0, cm1, newMerkleRoot, publicValueAbs, isUnshield);
  const dummyTx = { version: 2, inputs: [], outputs: [], locktime: 0 };
  const unlocking = unlocker.generateUnlockingBytecode
    ? unlocker.generateUnlockingBytecode({ transaction: dummyTx, sourceOutputs: [], inputIndex: 5 })
    : unlocker;

  // full 6-input transaction: the 5 verifier inputs with the genesis n0/n1 patched to
  // this scenario's proven public inputs, plus the pool covenant input.
  const verifierInputs = vectors.steps.map((s, n) => {
    let ub = Buffer.from(s.unlocking, 'hex');
    if (n === VERIFIER_INPUT_INDEX) {
      ub = Buffer.from(ub);                       // copy before patching
      provenRoot.copy(ub, N0_OFFSET);             // n0 DATA @ 1825
      provenActionHash.copy(ub, N1_OFFSET);       // n1 DATA @ 1792
    }
    return {
      outpointTransactionHash: new Uint8Array(32), outpointIndex: n, sequenceNumber: 0,
      unlockingBytecode: ub,
    };
  });
  const poolInput = {
    outpointTransactionHash: new Uint8Array(32), outpointIndex: 5, sequenceNumber: 0,
    unlockingBytecode: unlocking,
  };
  const allInputs = [...verifierInputs, poolInput];

  const sourceOutputs = [
    ...vectors.steps.map((s) => ({ lockingBytecode: Buffer.from(s.locking, 'hex'), valueSatoshis: 1000n })),
    { lockingBytecode: redeemScript, valueSatoshis: 1000n, token: mkToken('mutable', inCommitment, currentBalance) },
  ];
  const outputs = [
    { lockingBytecode: redeemScript, valueSatoshis: 1000n, token: mkToken('mutable', outCommitment, newBalance) },
  ];
  // unshield: a public PUSD payout output of publicValueAbs must exist at index 1.
  if (isUnshield === 1n) {
    outputs.push({ lockingBytecode: new Uint8Array([0x6a]), valueSatoshis: 546n, token: { amount: publicValueAbs, category } });
  }

  const program = { inputIndex: 5, sourceOutputs, transaction: { version: 2, inputs: allInputs, outputs, locktime: 0 } };

  // the bench grades our densless-msm impl on the STANDARD BCH 2026 VM (no vm:'bch-spec'),
  // so the pool covenant must validate there too.
  const vm = createVirtualMachineBch2026(true);
  const state = vm.evaluate(program);
  const top = state.stack[state.stack.length - 1];
  const accepted = state.error === undefined && state.stack.length === 1 &&
    top !== undefined && top.length === 1 && top[0] === 1;

  // per-input op-cost budget for the BCH 2026 VM: (41 + unlockingLen) * 800.
  const opCostBudget = (41 + unlocking.length) * 800;
  const operationCost = state.metrics?.operationCost ?? 0;

  return {
    label,
    accepted,
    error: state.error ?? null,
    stackDepth: state.stack.length,
    poolUnlockingBytes: unlocking.length,
    poolRedeemBytes: redeemScript.length,
    newBalance: newBalance.toString(),
    opCostBudget,
    operationCost,
    opCostWithinBudget: operationCost <= opCostBudget,
    metrics: state.metrics ?? null,
  };
};

// ── augment each scenario proof with the LE byte form of its proven n0/n1 ──────
// publicSignals = [merkleRoot, actionHash] (decimal strings). The covenant reads the
// 32-byte LE VM-number form from the genesis witness, so convert here.
const bigIntToVmNumber = (value) => {
  let v = BigInt(value);
  if (v === 0n) return Buffer.alloc(0);
  const neg = v < 0n; if (neg) v = -v;
  const bytes = []; while (v > 0n) { bytes.push(Number(v & 0xffn)); v >>= 8n; }
  if (bytes[bytes.length - 1] & 0x80) bytes.push(neg ? 0x80 : 0);
  else if (neg) bytes[bytes.length - 1] |= 0x80;
  return Buffer.from(bytes);
};
// pad/truncate a VM-number buffer to exactly 32 bytes (the field elements are < 2^254,
// so their VM-number form is already 32 bytes; left-pad with zeros just in case).
const to32LE = (bi) => {
  const b = bigIntToVmNumber(bi);
  const out = Buffer.alloc(32, 0);
  b.copy(out, 0);
  return out;
};

const scenarios = evalProofs.map((p) => ({
  label: `${p.label} (isUnshield=${p.covenant.isUnshield}, publicValueAbs=${p.covenant.publicValueAbs})`,
  covenant: p.covenant,
  merkleRootLE: to32LE(p.publicSignals[0]),
  actionHashLE: to32LE(p.publicSignals[1]),
}));

const results = scenarios.map(runScenario);

console.log(JSON.stringify(results, null, 2));
process.exit(results.every((r) => r.accepted && r.opCostWithinBudget) ? 0 : 1);
